/* ============================================================================
   НАСТРОЙКИ САЙТА — единственный файл, который правится под нового клиента.

   Здесь живут: название, контакты, услуги, цены, пакеты, отзывы, тексты блоков,
   акцентный цвет и привязка фотографий. Компоненты в client/src/pages/Home.tsx
   ничего не знают о конкретном детейлинг-центре — они только показывают эти данные.

   Как поднять сайт для нового центра:

     1. Замените brand, theme, seo, location, hero и тексты блоков ниже.
     2. Перепишите services, works, packages, process, brands.
     3. Фотографии клиента положите в raw/photos/ (имена файлов любые, .jpg).
        В photos укажите, какой файл какому слоту соответствует.
     4. node scripts/prepare-images.mjs   — нарежет из них webp в client/public/img
     5. node scripts/make-favicon.mjs     — перерисует фавикон из монограммы
     6. pnpm build                        — собрать сайт

   Проверка, что ни одна картинка не потерялась: node scripts/check-images.mjs

   Внутри текстов можно использовать <em>…</em> — это курсивная вставка
   акцентным шрифтом (заголовки вида «Броня <em>для вашего</em> автомобиля.»).
   ========================================================================== */

export type Service = {
  /** Ключ кадра: так же называется слот в photos ниже. */
  photo: string;
  title: string;
  note: string;
  /** Строка как её видит клиент. Из цифр внутри берётся цена для формы записи. */
  price: string;
  detail: string;
};

export type WorkItem = {
  label: string;
  service: string;
  result: string;
  /** Слот из photos. */
  photo: string;
  /** Размер плитки в сетке работ: lead — крупная, wide/tall/std — обычные. */
  variant: "lead" | "wide" | "tall" | "std";
};

export type Pack = {
  /** Короткое имя пакета, оно же показывается крупно под заголовком. */
  name: string;
  title: string;
  price: string;
  items: string[];
  cta: string;
};

export type BookingOption = {
  name: string;
  price: number;
  /** К какой услуге относится — по ней услуга и открывает форму записи. */
  service?: string;
};

